    '    REG_PAYLOAD=$(cat <<EOF',
    '{',
    '  "registrationCode": "$REG_CODE",',
    '  "computerName": "$HOSTNAME",',
    '  "osName": "$OS_NAME $OS_VER",',
    '  "osVersion": "$OS_VER",',
    '  "osBuild": "$OS_VER",',
    '  "osArchitecture": "$ARCH",',
    '  "cpuModel": "$(uname -m) Processor",',
    '  "cpuCores": $CORES,',
    '  "cpuLogicalProcessors": $CORES,',
    '  "totalRamBytes": 17179869184,',
    '  "motherboard": "Generic System Board",',
    '  "biosVersion": "1.0",',
    '  "serialNumber": "SN-$HOSTNAME",',
    '  "gpuModel": "Standard Display Adapter",',
    '  "isLaptop": false,',
    '  "agentVersion": "2.4.0-sh"',
    '}',
    'EOF',
    ')',
    '    RESP=$(curl -s -X POST "$SERVER_URL/api/agent/register" \\',
    '        -H "Content-Type: application/json" \\',
    '        -d "$REG_PAYLOAD")',
    '',
    '    DEVICE_TOKEN=$(echo "$RESP" | grep -o \'"token": *"[^"]*"\' | cut -d\'"\' -f4)',
    '    if [ -z "$DEVICE_TOKEN" ]; then',
    '        DEVICE_TOKEN=$(echo "$RESP" | grep -o \'"deviceToken": *"[^"]*"\' | cut -d\'"\' -f4)',
    '    fi',
    '    DEVICE_ID=$(echo "$RESP" | grep -o \'"deviceId": *"[^"]*"\' | cut -d\'"\' -f4)',
    '',
    '    if [ -n "$DEVICE_TOKEN" ]; then',
    '        echo "{\\"server\\":\\"$SERVER_URL\\",\\"token\\":\\"$DEVICE_TOKEN\\",\\"deviceId\\":\\"$DEVICE_ID\\"}" > "$TOKEN_FILE"',
    '        echo "[SUCCESS] Registered Device ID: $DEVICE_ID"',
    '    else',
    '        echo "[ERROR] Registration failed: $RESP"',
    '        echo ""',
    '        echo "--- FIX CONNECTION GUIDE ---"',
    '        echo "1. If in preview sandbox: Use the In-Browser Dev Simulator in the dashboard."',
    '        echo "2. If testing locally: start app (npm run dev) and set SERVER_URL=\\"http://localhost:3000\\""',
    '        exit 1',
