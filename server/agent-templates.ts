    '  return new Promise((resolve, reject) => {',
    '    const parsed = new URL(url);',
    '    const client = parsed.protocol === "https:" ? https : http;',
    '    const headers = { "Content-Type": "application/json" };',
    '    if (token) headers["Authorization"] = `Bearer ${token}`;',
    '    const body = data ? JSON.stringify(data) : "";',
    '    headers["Content-Length"] = Buffer.byteLength(body);',
    '',
    '    const req = client.request(parsed, { method, headers }, res => {',
    '      let raw = "";',
    '      res.on("data", chunk => raw += chunk);',
    '      res.on("end", () => {',
    '        try { resolve({ status: res.statusCode, data: JSON.parse(raw) }); } catch(e) { resolve({ status: res.statusCode, raw }); }',
    '      });',
    '    });',
    '    req.on("error", reject);',
    '    if (body) req.write(body);',
    '    req.end();',
    '  });',
    '}',
    '',
    'async function run() {',
    '  if (!deviceToken) {',
    '    const specs = {',
    '      registrationCode: REG_CODE,',
    '      computerName: os.hostname(),',
    '      osName: `${os.type()} ${os.release()}`,',
    '      osVersion: os.release(),',
    '      osBuild: os.version ? os.version() : "1.0",',
