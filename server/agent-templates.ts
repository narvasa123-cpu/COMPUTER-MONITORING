    'console.log("  PC & LAPTOP MONITORING & DIAGNOSTIC AGENT (NODE.JS)  ");',
    'console.log("=======================================================");',
    'console.log(`Target Server: ${SERVER_URL}`);',
    '',
    'let deviceToken = null;',
    'let deviceId = null;',
    '',
    'if (fs.existsSync(TOKEN_FILE)) {',
