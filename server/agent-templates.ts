/**
 * Generates standalone, fully functional monitoring agent scripts
 * with the server URL and device registration token pre-configured or parameter-ready.
 */

function sanitizeServerUrl(url: string): string {
  let u = (url || '').trim();
  if (u.includes('.run.app') || u.includes('cloudrun')) {
    u = u.replace(/^http:\/\//i, 'https://');
  }
  return u;
}

