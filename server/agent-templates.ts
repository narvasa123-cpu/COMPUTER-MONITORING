    '                    if ($sample.Path -match "Bytes Sent/sec") { $bytesOutPerSec += [math]::Max(0, $sample.CookedValue) }',
    '                }',
    '            }',
    '            $bytesInPerSec = [math]::Round($bytesInPerSec, 0)',
