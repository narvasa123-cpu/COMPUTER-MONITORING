    '',
    'let deviceToken = null;',
    'let deviceId = null;',
    '',
    'if (fs.existsSync(TOKEN_FILE)) {',
    '  try {',
    '    const cached = JSON.parse(fs.readFileSync(TOKEN_FILE, "utf-8"));',
    '    if (cached.server === SERVER_URL && (cached.token || cached.deviceToken)) {',
    '      deviceToken = cached.token || cached.deviceToken;',
    '      deviceId = cached.deviceId;',
    '      console.log(`[INFO] Loaded cached authentication token for Device: ${deviceId}`);',
    '    }',
    '  } catch (e) {}',
